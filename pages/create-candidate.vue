                let _rData = res.data.dataDutyHrm;
                
                // First convert the data to the required format
                const positions = _rData.map((x) => {
                    let name, code;
                    try {
                        name = JSON.parse(x.duty_name);
                    } catch (e) {
                        name = x.duty_name;
                    }
                    try {
                        code = JSON.parse(x.duty_no);
                    } catch (e) {
                        code = x.duty_no;
                    }
                    return {
                        id: x.id,
                        code: code,
                        name: typeof name === 'object' ? name : {
                            vi: name,
                            en: name,
                            cn: name
                        }
                    };
                });
                
                // Sort positions with C02 and B09 at the top
                this.item_position = positions.sort((a, b) => {
                    // Define priority order
                    const priorityOrder = ['C02', 'B09'];
                    
                    // Get index in priority array (-1 if not found)
                    const indexA = priorityOrder.indexOf(a.code);
                    const indexB = priorityOrder.indexOf(b.code);
                    
                    // If both items are in priority list, sort by priority order
                    if (indexA !== -1 && indexB !== -1) {
                        return indexA - indexB;
                    }
                    // If only a is in priority list, it comes first
                    if (indexA !== -1) return -1;
                    // If only b is in priority list, it comes first
                    if (indexB !== -1) return 1;
                    // For all other items, maintain original order
                    return 0;
                });
                
                // If position is already set as code/string, resolve to object
                if (this.position && typeof this.position !== 'object') {
                    const match = this.item_position.find(x => String(x.code) === String(this.position));
                    if (match) {
                        this.position = match;
                    }
                } else if (!this.position && this.loc_apply) {
                    const matchingPosition = this.item_position.find(pos => {
                        if (!pos || !pos.name) return false;
                        const names = typeof pos.name === 'object' ? Object.values(pos.name) : [pos.name];
                        const mapping = this.positionMapping[this.loc_apply] || [this.loc_apply];
                        return mapping.some(m => names.some(n => String(n).toLowerCase().includes(String(m).toLowerCase()))) || names.includes(this.loc_apply);
                    });
                    if (matchingPosition) {
                        this.position = matchingPosition;
                    }
                }
                
            } catch (error) {
                console.log(error);
            }
